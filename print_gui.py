def _find(name, timeout=15, confidence=0.8):
    path = TEMPLATES / name
    if not path.exists():
        have = sorted(p.name for p in TEMPLATES.glob("*")) if TEMPLATES.exists() else "(folder does not exist)"
        raise RuntimeError(f"Missing template image: {path}\nFiles found in {TEMPLATES}: {have}")
    end = time.time() + timeout
    while time.time() < end:
        try:
            box = pyautogui.locateCenterOnScreen(str(path), confidence=confidence)
        except pyautogui.ImageNotFoundException:
            box = None
        if box:
            return box
        time.sleep(0.5)
    return None


def _click(name, timeout=15, confidence=0.8):
    pos = _find(name, timeout, confidence)
    if not pos:
        shot = Path(__file__).with_name(f"debug_gui_{Path(name).stem}.png")
        pyautogui.screenshot(str(shot))
        raise RuntimeError(f"Could not see {name} on screen (screenshot: {shot.name})")
    pyautogui.click(pos.x, pos.y)


def focus_browser_window(title_hint=""):
    """Minimise this console and bring the automation browser window to the front,
    maximised, so the screen matching can see it (Windows only)."""
    import ctypes
    from ctypes import wintypes
    user32, kernel32 = ctypes.windll.user32, ctypes.windll.kernel32

    con = kernel32.GetConsoleWindow()
    if con:
        user32.ShowWindow(con, 6)                      # SW_MINIMIZE: console out of the way

    found = []
    EnumProc = ctypes.WINFUNCTYPE(ctypes.c_bool, wintypes.HWND, wintypes.LPARAM)

    def cb(hwnd, _):
        if user32.IsWindowVisible(hwnd):
            n = user32.GetWindowTextLengthW(hwnd)
            if n:
                buf = ctypes.create_unicode_buffer(n + 1)
                user32.GetWindowTextW(hwnd, buf, n + 1)
                found.append((hwnd, buf.value))
        return True

    user32.EnumWindows(EnumProc(cb), 0)
    hint = (title_hint or "").lower()
    pick = None
    for hwnd, title in found:                          # 1) window showing the page title
        if hint and hint[:25] in title.lower() and "powershell" not in title.lower():
            pick = hwnd
            break
    if not pick:                                       # 2) Playwright's Chromium
        for hwnd, title in found:
            t = title.lower()
            if "chromium" in t or "chrome for testing" in t:
                pick = hwnd
                break
    if not pick:
        raise RuntimeError("Could not find the automation browser window")
    user32.ShowWindow(pick, 9)                         # SW_RESTORE
    user32.ShowWindow(pick, 3)                         # SW_MAXIMIZE
    user32.keybd_event(0x12, 0, 0, 0)                  # tap Alt so Windows allows the focus change
    user32.keybd_event(0x12, 0, 2, 0)
    user32.SetForegroundWindow(pick)
    time.sleep(1.5)


def restore_console():
    """Bring the PowerShell window back after the automation (Windows only)."""
    import ctypes
    con = ctypes.windll.kernel32.GetConsoleWindow()
    if con:
        ctypes.windll.user32.ShowWindow(con, 9)        # SW_RESTORE
        ctypes.windll.user32.SetForegroundWindow(con)


def save_pdf_via_print_dialog(target: Path, window_hint: str = ""):
    """Run markers 1-4, then type the file name in the Windows 'Save As' box."""
    target = Path(target).resolve()
    if target.exists():
        target.unlink()

    focus_browser_window(window_hint)               # browser in front, console minimised
    _click("1_print_icon.png")                      # 1  print icon in the PDF viewer
    time.sleep(2)

    has_3b = (TEMPLATES / "3b_already_pdf.png").exists()
    if not (has_3b and _find("3b_already_pdf.png", timeout=4)):    # not yet on 'Save as PDF'
        _click("2_destination.png")                 # 2  open Destination list
        time.sleep(0.8)
        if (TEMPLATES / "3_save_as_pdf.png").exists():
            _click("3_save_as_pdf.png")             # 3  click the 'Save as PDF' row
        else:
            pyautogui.write("Save as", interval=0.12)   # 3  type-ahead in the list
            pyautogui.press("enter")
        time.sleep(1)
        if has_3b and not _find("3b_already_pdf.png", timeout=6):
            pyautogui.screenshot(str(Path(__file__).with_name("debug_gui_destination.png")))
            raise RuntimeError("Destination is not 'Save as PDF' (see debug_gui_destination.png)")

    _click("4_save.png")                            # 4  Save

    # Windows 'Save As' window: file name box has focus -> type full path, Enter
    time.sleep(2)
    pyautogui.hotkey("ctrl", "a")
    pyautogui.write(str(target), interval=0.02)
    pyautogui.press("enter")

    end = time.time() + 30
    while time.time() < end:
        if target.exists() and target.stat().st_size > 1000:
            time.sleep(1)
            if target.read_bytes()[:1024].find(b"%PDF") >= 0:
                return target
        time.sleep(0.5)
    raise RuntimeError(f"PDF file did not appear: {target}")
