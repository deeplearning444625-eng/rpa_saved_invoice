def _ensure_templates():
    import base64
    TEMPLATES.mkdir(exist_ok=True)
    for name, b64 in _BUILTIN.items():
        p = TEMPLATES / name
        if not p.exists():
            p.write_bytes(base64.b64decode(b64))


